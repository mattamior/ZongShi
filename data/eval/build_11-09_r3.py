def load_news() -> list[dict]:
    rows = []
    for path in NEWS_FILES:
        if path.exists():
            rows += [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    return rows


def interleave(rows: list[tuple]) -> list[tuple]:
    """按类别轮转排序，避免整段时间堆同一类。"""
    buckets: dict[str, list] = collections.OrderedDict()
    for row in rows:
        buckets.setdefault(row[0], []).append(row)
    out: list[tuple] = []
    while any(buckets.values()):
        for key in list(buckets):
            if buckets[key]:
                out.append(buckets[key].pop(0))
    return out


def slot_for(i: int) -> tuple[str, str]:
    """前 20 条排到 11-09 19:00–23:45，其余排到 11-10 00:00 起，每 15 分钟一个位。"""
    if i < 20:
        minutes = 19 * 60 + i * 15
        return "2026-11-09", f"{minutes // 60:02d}:{minutes % 60:02d}"
    minutes = (i - 20) * 15
    return "2026-11-10", f"{minutes // 60:02d}:{minutes % 60:02d}"


def main() -> None:
    news = load_news()
    ordered = interleave(ROWS)
    out_rows = []
    for i, (label, text, keyword, template) in enumerate(ordered):
        date, slot = slot_for(i)
        row = {
            "id": f"p{i + 1:03d}", "date": date, "slot": slot,
            "topic": CODE[label], "template": template,
            "claim": "assertion" if keyword else "observation",
            "text": text, "variant": "1",
        }
        if keyword:
            hit = next((n for n in news if keyword in n["title"]), None)
            if hit is None:
                raise SystemExit(f"p{i + 1:03d}: 热榜里找不到来源 {keyword!r}")
            row["source_url"] = hit["url"]
            row["source_title"] = hit["title"]
        out_rows.append(row)

    OUT_JSONL.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in out_rows), encoding="utf-8")

    counts = collections.Counter(label for label, _t, _k, _tp in ordered)
    key3 = counts["社会"] + counts["时政"] + counts["民生"]
    head = (f"# 2026-11-09 晚 → 11-10 候选（{len(out_rows)} 条）\n\n"
            f"社会 {counts['社会']} / 时政 {counts['时政']} / 民生 {counts['民生']}，"
            f"合计 **{key3}/{len(out_rows)} = {key3 / len(out_rows):.0%}**；"
            f"其余：科技 {counts['科技']}、消费 {counts['消费']}、产业 {counts['产业']}、"
            f"娱乐 {counts['娱乐']}、体育 {counts['体育']}。\n\n"
            "热点条目只取标题级信息，来源在 `data/news/2026-11-09*.jsonl`；观察类不引来源。"
            "全部挂 `@grok`，**未发布、未排期**。\n")
    lines = [head]
    for day in ("2026-11-09", "2026-11-10"):
        lines += [f"## {day}", ""]
        for r in out_rows:
            if r["date"] != day:
                continue
            lines += [f"### {r['id']} {r['slot']}·{r['template']}·{len(r['text'])}字", "",
                      "```", r["text"], "```", ""]
    lines += ["## 来源", ""]
    lines += [f"- {r['id']}：{r['source_title']}" for r in out_rows if r.get("source_title")]
    lines += ["", "## 限制", "",
              "- 热榜只到标题级核实，未打开原文；观察类写的是常见场景，未引用具体数据。",
              "- 全部人工撰写，未发布，无曝光与互动数据。", ""]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_JSONL.relative_to(ROOT)} ({len(out_rows)} 条)")
    print("类别:", dict(counts), "合计前四类:", key3)
    lens = sorted(len(r["text"]) for r in out_rows)
